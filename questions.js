      if (!chapterIds.has(q.chapterId)) report.invalidChapter.push(q.id);
      if (q.answer === "" || (Array.isArray(q.answer) && q.answer.length === 0)) report.emptyAnswers.push(q.id);
      if (!String(q.explanation || "").trim()) report.emptyExplanations.push(q.id);
      if (!report.chapters[q.chapterId]) report.chapters[q.chapterId] = { name: q.chapter, total: 0, single: 0, blank: 0, short: 0, essay: 0 };
